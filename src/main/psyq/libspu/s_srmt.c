s32 SpuSetReverbModeType(s32 mode) {
    SpuReverbParam attr;
    s32 clear;
    s32 on;
    u8* d;
    u8* s;
    u32 n;
    u16 c;

    clear = 0;
    if (mode & 0x100) {
        mode &= ~0x100;
        clear = 1;
    }
    if ((u32)mode >= 10 || _SpuIsInAllocateArea_(D_80058E70[mode])) {
        return -1;
    }
    D_800589B4.m4_mode = mode;
    D_800589B0 = D_80058E70[mode];
    d = (u8*)&attr;
    s = (u8*)&spuReverbPresets[mode];
    n = sizeof(SpuReverbParam);
    while (n--) {
        *d++ = *s++;
    }
    attr.m0_mask = 0;
    switch (mode) {
    case 7:
        D_800589B4.m10_feedback = 0x7F;
        D_800589B4.mC_delay = 0x7F;
        break;
    case 8:
        D_800589B4.m10_feedback = 0;
        D_800589B4.mC_delay = 0x7F;
        break;
    default:
        D_800589B4.m10_feedback = 0;
        D_800589B4.mC_delay = 0;
        break;
    }
    on = (_spu_RXX->m1AA_control & 0x80) != 0;
    if (on) {
        c = _spu_RXX->m1AA_control;
        c &= ~0x80;
        _spu_RXX->m1AA_control = c;
    }
    _spu_RXX->m184_revVolL = 0;
    _spu_RXX->m186_revVolR = 0;
    D_800589B4.m8_depth.m0_left = 0;
    D_800589B4.m8_depth.m2_right = 0;
    _spu_setReverbAttr(&attr);
    if (clear) {
        SpuClearReverbWorkArea(mode);
    }
    _spu_FsetRXX(0xD1, D_800589B0, 0);
    if (on) {
        c = _spu_RXX->m1AA_control;
        c |= 0x80;
        _spu_RXX->m1AA_control = c;
    }
    return 0;
}
