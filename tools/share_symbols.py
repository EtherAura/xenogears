#!/usr/bin/env python3
"""Give a second version the first version's symbol names, so both build from
the same C.

Regenerates the generated sections at the end of config/<b>/symbols/<mod>.txt:

  "Names shared with <A>": every function and data symbol that
      tools/map_versions.py pairs, at <b>'s addresses; plus <name>_<b> renames
      for <b>'s own labels whose splat names (func_/D_/jtbl_ + address) a
      shared name would otherwise take over.
  "Renames for other modules": the same renames for addresses <b>'s other
      modules refer to, since they read this symbol file too.

Everything above those sections is hand-written and wins over the mapping.
Mapping and collisions both use a disassembly of <b> made with only the
hand-written names ("native"), so the result does not feed back on itself.

    python tools/share_symbols.py us jp main
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEN = "// ---- Names shared with {a} (generated by tools/share_symbols.py) ----"
OTHER = "// ---- Renames for other modules (generated by tools/share_symbols.py) ----"
ADDR_NAME = re.compile(r"^(?:func|D|jtbl)_([0-9A-F]{8})$")
LABEL = re.compile(r"^(glabel|dlabel|jlabel) (\w+)$")


def run(*cmd: str) -> str:
    p = subprocess.run([sys.executable, *cmd], cwd=ROOT, capture_output=True, text=True)
    if p.returncode != 0:
        sys.exit(f"{' '.join(cmd)} failed:\n{(p.stdout + p.stderr)[-3000:]}")
    return p.stdout


def split_file(path: Path) -> tuple[str, str]:
    """(hand-written part, other-module renames) of a symbol file."""
    text = path.read_text()
    base = re.split(r"(?m)^// ---- Names shared with ", text)[0]
    other = ""
    if OTHER in text:
        other = text[text.index(OTHER) + len(OTHER):].strip("\n")
        base = base.split(OTHER)[0]
    return base.rstrip("\n") + "\n", other


def labels(asm_dir: Path) -> dict[str, tuple[int, str]]:
    """name -> (address, kind) for every label in a disassembly."""
    out = {}
    for f in asm_dir.rglob("*.s"):
        lines = f.read_text().splitlines()
        for i, t in enumerate(lines):
            m = LABEL.match(t)
            if not m:
                continue
            for nxt in lines[i + 1:i + 4]:
                a = re.search(r"/\* (?:\w+ )?([0-9A-F]{8}) ", nxt)
                if a:
                    out.setdefault(m.group(2), (int(a.group(1), 16), m.group(1)))
                    break
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("a")
    ap.add_argument("b")
    ap.add_argument("module")
    ap.add_argument("--iterations", type=int, default=6)
    args = ap.parse_args()

    symfile = ROOT / "config" / args.b / "symbols" / f"{args.module}.txt"
    base, _ = split_file(symfile)
    other = ""
    header = GEN.format(a=args.a.upper())
    tmp = ROOT / "work" / "tmp"
    tmp.mkdir(parents=True, exist_ok=True)

    # Native labels: b disassembled with only its hand-written names.
    (tmp / "native_syms.txt").write_text(base)
    run("tools/fullasm.py", args.b, args.module, "--symbols", str(tmp / "native_syms.txt"),
        "--out", f"{args.module}_native")
    native = labels(ROOT / "work" / "fullasm" / args.b / f"{args.module}_native" / "asm")
    run("tools/fullasm.py", args.a, args.module)

    def write(gen_lines: list[str]) -> None:
        nonlocal other
        used = {int(a, 16) for a in re.findall(r"=\s*0x([0-9A-Fa-f]{8})", base + "\n".join(gen_lines))}
        # drop other-module renames whose address the mapping now names
        other = "\n".join(l for l in other.splitlines()
                          if not re.search(r"=\s*0x([0-9A-Fa-f]{8})", l)
                          or int(re.search(r"=\s*0x([0-9A-Fa-f]{8})", l).group(1), 16) not in used)
        text = base + "\n" + header + "\n" + "\n".join(gen_lines) + "\n"
        if other:
            text += "\n" + OTHER + "\n" + other + "\n"
        symfile.write_text(text)

    # start from the current generated names, minus stale renames
    text = symfile.read_text()
    current = []
    if header in text:
        current = [l for l in text.split(header)[1].split(OTHER)[0].splitlines() if l.strip()]
    write(current)

    # Attributes added by hand to generated lines (force_not_migration, a
    # type:func tag the mapping lacks, notes) survive regeneration as long as
    # the name keeps its address.
    entry = re.compile(r"^(\w+)\s*=\s*0x([0-9A-Fa-f]{8});\s*(?://\s*(.*))?$")
    kept_attrs = {}
    for l in current:
        m = entry.match(l)
        if m and m.group(3):
            kept_attrs[(m.group(1), int(m.group(2), 16))] = m.group(3)

    # A name for the start of one of b's own functions is a function: without
    # type:func the generated data assignment would turn the code symbol
    # absolute (the build still matches, but progress skips the C). So is
    # splat's name for one (func_), here for another module's function b calls
    # (field_debug's from field, main's): the PC link (tools/pc_link.py) takes
    # an unmarked name no symbol file calls a function for data (xg-ves).
    func_starts = {addr for addr, kind in native.values() if kind == "glabel"}

    def keep_attrs(l: str) -> str:
        m = entry.match(l)
        if not m:
            return l
        name, addr = m.group(1), int(m.group(2), 16)
        old = kept_attrs.get((name, addr))
        new = m.group(3) or ""
        if old and new in old:
            new = old
        if (addr in func_starts or name.startswith("func_")) and "type:func" not in new:
            new = "type:func" + (f" {new}" if new else "")
        return f"{name} = 0x{addr:08X};" + (f" // {new}" if new else "")

    previous = None
    native_asm = ROOT / "work" / "fullasm" / args.b / f"{args.module}_native" / "asm"
    for i in range(args.iterations):
        out = tmp / "shared_syms.txt"
        run("tools/map_versions.py", args.a, args.b, args.module, "--symbols", str(out),
            "--b-asm", str(native_asm))
        lines = [keep_attrs(l) for l in out.read_text().splitlines() if l.strip()]
        if args.module != "main":
            # An overlay reads main.txt too. A pairing that gives one of its
            # names another address is an operand pairing gone wrong: e.g. CDK
            # code reaching a struct field as base + offset, while the other
            # version's compiler loads the field's full address.
            main_syms = {m.group(1): int(m.group(2), 16) for m in re.finditer(
                r"^(\w+)\s*=\s*0x([0-9A-Fa-f]{8});",
                (ROOT / "config" / args.b / "symbols" / "main.txt").read_text(), re.M)}
            kept = []
            for l in lines:
                name, addr = l.split(" = ")[0], int(l.split(" = ")[1][2:10], 16)
                if main_syms.get(name, addr) != addr:
                    print(f"skipped {name} = 0x{addr:08X} (main.txt: 0x{main_syms[name]:08X})", file=sys.stderr)
                    continue
                kept.append(l)
            lines = kept
        given = {l.split(" = ")[0]: int(l.split(" = ")[1][2:10], 16) for l in lines}
        taken = set(given.values()) | {int(a, 16) for a in re.findall(r"=\s*0x([0-9A-Fa-f]{8})", base)}
        renames = []
        for name, addr in sorted(given.items()):
            m = ADDR_NAME.match(name)
            if not m or int(m.group(1), 16) == addr or name not in native:
                continue
            naddr, kind = native[name]
            if naddr in taken:
                continue
            taken.add(naddr)
            renames.append(f"{name}_{args.b} = 0x{naddr:08X};" + (" // type:func" if kind == "glabel" else ""))
        gen = lines + renames
        write(gen)
        print(f"iteration {i + 1}: {len(lines)} shared names, {len(renames)} renames")
        if gen == previous:
            break
        previous = gen
    run("tools/fullasm.py", args.b, args.module)

    # Other modules of b read main's symbol file too (an overlay's file is
    # read only by that overlay). Where one of them refers to its own address
    # whose splat name a shared name has taken, rename that address. Judged
    # on native disassemblies of those modules, in which an address-style
    # name appears only for the address it spells.
    if args.module != "main":
        text = symfile.read_text().split(OTHER)[0].rstrip("\n") + "\n"
        symfile.write_text(text)
        run("tools/configure.py")  # every version: build.ninja covers them all
        return
    given = {}
    for m in re.finditer(r"^(\w+)\s*=\s*0x([0-9A-Fa-f]{8});", symfile.read_text(), re.M):
        given.setdefault(m.group(1), int(m.group(2), 16))
    taken = set(given.values())
    renames = []
    for cfg in sorted((ROOT / "config" / args.b).glob("*.yaml")):
        mod = cfg.stem
        if mod in (args.module, "splat", "disc"):
            continue
        own = ROOT / "config" / args.b / "symbols" / f"{mod}.txt"
        syms = [str(tmp / "native_syms.txt")] + ([str(own)] if own.is_file() else [])
        run("tools/fullasm.py", args.b, mod, "--symbols", *syms, "--out", f"{mod}_native")
        # names the symbol files define mean their defined address; only
        # splat's automatic names spell the address they stand for
        defined = set(re.findall(r"^(\w+)\s*=", base + (own.read_text() if own.is_file() else ""), re.M))
        for f in (ROOT / "work" / "fullasm" / args.b / f"{mod}_native" / "asm").rglob("*.s"):
            for name in sorted(set(re.findall(r"\b(?:func|D|jtbl)_[0-9A-F]{8}\b", f.read_text())) - defined):
                addr = int(name[-8:], 16)
                if name in given and given[name] != addr and addr not in taken:
                    taken.add(addr)
                    kind = " // type:func" if name.startswith("func_") else ""
                    renames.append(f"{name}_{args.b} = 0x{addr:08X};{kind}")
    other = "\n".join(renames)
    text = symfile.read_text().split(OTHER)[0].rstrip("\n") + "\n"
    if other:
        text += "\n" + OTHER + "\n" + other + "\n"
    symfile.write_text(text)
    print(f"other modules: {len(renames)} renames")
    run("tools/configure.py")  # every version: build.ninja covers them all


if __name__ == "__main__":
    main()
